"""
Re-useable fixtures etc. for tests

See https://docs.pytest.org/en/7.1.x/reference/fixtures.html#conftest-py-sharing-fixtures-across-multiple-files
"""

import os
import tomllib
from dataclasses import dataclass
from functools import cached_property
from pathlib import Path
from typing import Any

import pytest
import yaml

ROOT = Path(__file__).parents[1]
ACTION = ROOT / "actions" / "record-bundle"
CTT_DIR = Path(__file__).parent / "regression" / "ctt"

# The version the generated recipe declares, and the bundle directory it lands in.
VERSION = "v0.1.0"
BUNDLE = f"bundle/{VERSION}"

COPIER = yaml.safe_load((ROOT / "copier.yaml").read_text())

# uv resolves against an active environment, so this repository's own venv is dropped
# rather than inherited by a rendered feedstock.
ENV = {name: value for name, value in os.environ.items() if name != "VIRTUAL_ENV"}

# Copier's settings start with an underscore, so what is left is what a user answers.
QUESTIONS = {
    name: value
    for name, value in COPIER.items()
    if not name.startswith("_") and isinstance(value, dict)
}

# Build products rather than shipped files.
# Running the regression fixture leaves an environment, a cached input and a recorded
# bundle behind, and none of them came out of the template.
BUILD_PRODUCTS = frozenset(
    {".venv", ".git", ".cache", ".ruff_cache", "__pycache__", "bundle", "uv.lock"}
)


def shipped_paths(root: Path) -> list[str]:
    """Return the generated paths under a directory, relative and sorted."""
    return sorted(
        str(path.relative_to(root))
        for path in root.rglob("*")
        if path.is_file()
        and not BUILD_PRODUCTS.intersection(path.relative_to(root).parts)
    )


def shipped_files(root: Path) -> dict[str, bytes]:
    """Return the generated files under a directory, without any build products."""
    return {name: (root / name).read_bytes() for name in shipped_paths(root)}


def uses_lines(path: Path) -> list[str]:
    """Return the stripped `uses:` lines of a workflow."""
    return [
        line.strip()
        for line in path.read_text().splitlines()
        if line.lstrip().startswith("uses:")
    ]


def ctt_cases() -> dict[str, dict[str, Any]]:
    """Return the answer set behind each ctt output directory, keyed by its name."""
    config = tomllib.loads((ROOT / "ctt.toml").read_text())
    defaults = config.get("defaults", {})
    return {
        output.rsplit("/", 1)[-1]: {**defaults, **overrides}
        for output, overrides in config.get("output", {}).items()
    }


CASES = ctt_cases()


@dataclass(frozen=True)
class Feedstock:
    """One feedstock generated by copier-template-tester from a set of answers."""

    name: str
    path: Path
    answers: dict[str, Any]

    def read(self, relative: str) -> str:
        """Return the text of a generated file."""
        return (self.path / relative).read_text()

    @cached_property
    def recipe(self) -> dict[str, Any]:
        """The parsed record recipe."""
        return yaml.safe_load(self.read("bookshelf.yaml"))

    def book(self, version: str) -> dict[str, Any]:
        """Return the book the recipe declares for a version."""
        return next(book for book in self.recipe["books"] if book["version"] == version)

    def shipped(self) -> list[str]:
        """Return the generated paths, relative and sorted, without build products."""
        return shipped_paths(self.path)


def generated_feedstocks() -> list[Feedstock]:
    """Return every feedstock that ctt has generated under the regression directory."""
    return [
        Feedstock(
            name=path.name,
            path=path,
            answers=yaml.safe_load((path / ".copier-answers.yml").read_text()),
        )
        for path in sorted(CTT_DIR.iterdir())
        if (path / ".copier-answers.yml").exists()
    ]


FEEDSTOCKS = generated_feedstocks()

# ctt writes these, so an empty list means the fixtures were never generated and the
# parametrised tests would all quietly collect nothing.
assert FEEDSTOCKS, f"no generated feedstocks under {CTT_DIR}, run `make ctt`"


@pytest.fixture(params=FEEDSTOCKS, ids=lambda generated: generated.name)
def feedstock(request: pytest.FixtureRequest) -> Feedstock:
    """Run a test once per generated feedstock."""
    return request.param


@pytest.fixture
def feedstocks() -> list[Feedstock]:
    """Every generated feedstock at once, for comparisons across answers."""
    return FEEDSTOCKS
