"""
Re-useable fixtures etc. for tests

See https://docs.pytest.org/en/7.1.x/reference/fixtures.html#conftest-py-sharing-fixtures-across-multiple-files
"""

import ast
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest
import yaml

ROOT = Path(__file__).parents[1]
CTT_DIR = Path(__file__).parent / "regression" / "ctt"

# Build products rather than shipped files.
# Running the regression fixture leaves an environment, a cached input and a recorded
# bundle behind, and none of them came out of the template.
BUILD_PRODUCTS = frozenset(
    {".venv", ".git", ".cache", ".ruff_cache", "__pycache__", "bundle", "uv.lock"}
)


@dataclass(frozen=True)
class Feedstock:
    """One feedstock generated by copier-template-tester from a set of answers."""

    name: str
    path: Path
    answers: dict[str, Any]

    def read(self, relative: str) -> str:
        """Return the text of a generated file."""
        return (self.path / relative).read_text()

    def build_assignments(self, *names: str) -> dict[str, Any]:
        """Evaluate the named module level literal assignments in the build file."""
        tree = ast.parse(self.read("build.py"))
        return {
            node.targets[0].id: ast.literal_eval(node.value)
            for node in tree.body
            if isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id in names
        }

    def shipped(self) -> list[str]:
        """Return the generated paths, relative and sorted, without build products."""
        return sorted(
            str(path.relative_to(self.path))
            for path in self.path.rglob("*")
            if path.is_file()
            and not BUILD_PRODUCTS.intersection(path.relative_to(self.path).parts)
        )


def generated_feedstocks() -> list[Feedstock]:
    """Return every feedstock that ctt has generated under the regression directory."""
    return [
        Feedstock(
            name=path.name,
            path=path,
            answers=yaml.safe_load((path / ".copier-answers.yml").read_text()),
        )
        for path in sorted(CTT_DIR.iterdir())
        if (path / ".copier-answers.yml").exists()
    ]


FEEDSTOCKS = generated_feedstocks()

# ctt writes these, so an empty list means the fixtures were never generated and the
# parametrised tests would all quietly collect nothing.
assert FEEDSTOCKS, f"no generated feedstocks under {CTT_DIR}, run `make ctt`"


@pytest.fixture(params=FEEDSTOCKS, ids=lambda generated: generated.name)
def feedstock(request: pytest.FixtureRequest) -> Feedstock:
    """Run a test once per generated feedstock."""
    return request.param


@pytest.fixture
def feedstocks() -> list[Feedstock]:
    """Every generated feedstock at once, for comparisons across answers."""
    return FEEDSTOCKS
